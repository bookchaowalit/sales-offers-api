"""Characterizes cellkit.sqlgen: the generated migration and roles SQL, and what PostgreSQL then enforces."""

from __future__ import annotations

import uuid

import cellkit_support as support
import psycopg
import pytest
from cellkit_support import in_workspace

from cellkit import sqlgen
from cellkit.spec import parse


def norm(sql: str) -> str:
    return " ".join(sql.split())


def test_literals_are_quoted_and_json_is_cast():
    assert sqlgen._literal(True) == "true"
    assert sqlgen._literal(False) == "false"
    assert sqlgen._literal(3) == "3"
    assert sqlgen._literal(2.5) == "2.5"
    assert sqlgen._literal("it's") == "'it''s'"
    assert sqlgen._literal([1, "a'b"]) == "'[1, \"a''b\"]'::jsonb"
    assert sqlgen._literal({"k": "v'"}) == "'{\"k\": \"v''\"}'::jsonb"


def test_column_definitions_follow_the_spec(mini_cell):
    widget = mini_cell.resource("widget")
    column = {f.name: norm(sqlgen.column(mini_cell, f)) for f in widget.fields}

    assert column["title"] == (
        "title text NOT NULL CHECK (length(title) <= 120 AND length(title) >= 1)"
    )
    assert column["code"] == "code text CHECK (code IS NULL OR (length(code) <= 20))"
    assert column["status"] == (
        "status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'active'))"
    )
    assert column["category"] == (
        "category text CHECK (category IS NULL OR (category IN ('alpha', 'beta')))"
    )
    assert column["quantity"] == (
        "quantity integer NOT NULL DEFAULT 1 CHECK (quantity >= 0 AND quantity <= 100)"
    )
    assert column["weight"] == (
        "weight double precision CHECK (weight IS NULL OR (weight >= 0))"
    )
    assert column["active"] == "active boolean NOT NULL DEFAULT true"
    assert column["starts_on"] == "starts_on date"
    assert column["seen_at"] == "seen_at timestamptz"
    assert column["meta"] == (
        "meta jsonb CHECK (meta IS NULL OR (jsonb_typeof(meta) = 'object'))"
    )
    assert column["tags"] == (
        "tags jsonb CHECK (tags IS NULL OR (jsonb_typeof(tags) = 'array'))"
    )
    assert column["parent_id"] == "parent_id bigint"


def test_a_required_field_with_a_default_and_an_enum_quote_escaping():
    cell = parse(
        {
            "cell": "quote-check",
            "resources": {
                "thing": {
                    "fields": {
                        "label": {
                            "type": "enum",
                            "values": ["it's", "plain"],
                            "required": True,
                            "default": "it's",
                        },
                        "qty": {"type": "int", "min": 1, "default": 1},
                    }
                }
            },
        }
    )
    thing = cell.resource("thing")
    label = norm(sqlgen.column(cell, thing.field("label")))
    assert label == (
        "label text NOT NULL DEFAULT 'it''s' CHECK (label IN ('it''s', 'plain'))"
    )
    assert norm(sqlgen.column(cell, thing.field("qty"))) == (
        "qty integer NOT NULL DEFAULT 1 CHECK (qty >= 1)"
    )


def test_table_carries_tenancy_identity_uniques_and_refs(mini_cell):
    widget = mini_cell.resource("widget")
    text = sqlgen.table(mini_cell, widget)

    assert "workspace_id             uuid NOT NULL" in text
    assert "GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000)" in text
    assert "PRIMARY KEY (workspace_id, id)" in text
    assert "UNIQUE (workspace_id, code)" in text
    assert "UNIQUE (workspace_id, title, category)" in text
    # the self-ref points at the same table
    assert (
        "FOREIGN KEY (workspace_id, parent_id) REFERENCES kit_sample.widgets (workspace_id, id)"
        in text
    )
    assert (
        "CREATE UNIQUE INDEX widgets_legacy ON kit_sample.widgets (workspace_id, legacy_id)"
        " WHERE legacy_id IS NOT NULL;"
    ) in text
    # indexes: filters and refs, sorted by name
    indexes = [line for line in text.splitlines() if line.startswith("CREATE INDEX")]
    assert [line.split()[2] for line in indexes] == [
        "widgets_category",
        "widgets_parent_id",
        "widgets_status",
    ]


def test_child_table_references_its_parent(mini_cell):
    part = mini_cell.resource("part")
    text = sqlgen.table(mini_cell, part)
    assert (
        "FOREIGN KEY (workspace_id, widget_id) REFERENCES kit_sample.widgets (workspace_id, id)"
        in text
    )
    assert (
        "CREATE INDEX parts_widget_id ON kit_sample.parts (workspace_id, widget_id);"
        in text
    )


def test_migration_creates_parents_first_and_enables_row_security(mini_cell):
    sql = sqlgen.migration(mini_cell)

    assert sql.startswith("-- Kit sample cell (kit-sample), generated by solo-cell-kit")
    assert "CREATE SCHEMA kit_sample;" in sql
    assert "CREATE FUNCTION kit_sample.current_workspace() RETURNS uuid" in sql
    # a ref target is created before the table that points at it
    assert sql.index("CREATE TABLE kit_sample.widgets") < sql.index(
        "CREATE TABLE kit_sample.parts"
    )
    assert "CREATE TABLE kit_sample.create_keys" in sql
    assert "CREATE TABLE kit_sample.outbox" in sql
    assert "ARRAY['widgets', 'parts', 'create_keys', 'outbox']" in sql, (
        "every tenant table gets the same row-level policy"
    )
    assert "FORCE ROW LEVEL SECURITY" in sql
    assert "USING (workspace_id = kit_sample.current_workspace())" in sql


def test_migration_grants_only_what_each_role_needs(mini_cell):
    sql = sqlgen.migration(mini_cell)
    api, publisher = mini_cell.role("api"), mini_cell.role("publisher")

    assert (
        f"GRANT SELECT, INSERT, UPDATE, DELETE ON kit_sample.widgets, kit_sample.parts TO {api};"
        in sql
    )
    assert (
        f"GRANT UPDATE (execution_id, published_at, attempts, next_attempt_at, last_error) "
        f"ON kit_sample.outbox TO {api};" in sql
    )
    assert (
        f"CREATE POLICY publisher_sweep ON kit_sample.outbox TO {publisher} USING (true) WITH CHECK (true);"
        in sql
    )
    assert f"GRANT SELECT ON kit_sample.outbox TO {publisher};" in sql
    # the publisher may mark rows but never change their content
    assert (
        f"GRANT UPDATE (published_at, attempts, next_attempt_at, last_error) "
        f"ON kit_sample.outbox TO {publisher};" in sql
    )


def test_roles_sql_names_three_roles_and_is_rerunnable(mini_cell, mini_cluster):
    sql = sqlgen.roles(mini_cell)
    for role in (
        mini_cell.role("migrator"),
        mini_cell.role("api"),
        mini_cell.role("publisher"),
    ):
        assert f"CREATE ROLE {role} LOGIN" in sql
        assert f"rolname = '{role}'" in sql
    assert "NOBYPASSRLS" in sql
    # the cluster already has the roles from bootstrap; running the script again must not fail
    with mini_cluster.connect("postgres", "postgres", autocommit=True) as conn:
        conn.execute(sql)


def test_the_database_enforces_the_generated_constraints(mini_cell, mini_cluster):
    ws = uuid.uuid4()
    api = mini_cell.role("api")
    [(widget_id,)] = in_workspace(
        mini_cluster,
        api,
        ws,
        "INSERT INTO kit_sample.widgets (workspace_id, title, code) VALUES"
        " (current_setting('app.workspace_id')::uuid, 'Alpha', 'A-1') RETURNING id",
    )
    assert widget_id >= 1_000_000, "new ids start above the legacy limit"

    with pytest.raises(psycopg.errors.CheckViolation):
        in_workspace(
            mini_cluster,
            api,
            ws,
            "INSERT INTO kit_sample.widgets (workspace_id, title, status) VALUES"
            " (current_setting('app.workspace_id')::uuid, 'Bad', 'archived')",
        )
    with pytest.raises(psycopg.errors.UniqueViolation):
        in_workspace(
            mini_cluster,
            api,
            ws,
            "INSERT INTO kit_sample.widgets (workspace_id, title, code) VALUES"
            " (current_setting('app.workspace_id')::uuid, 'Again', 'A-1')",
        )
    with pytest.raises(psycopg.errors.ForeignKeyViolation):
        in_workspace(
            mini_cluster,
            api,
            ws,
            "INSERT INTO kit_sample.parts (workspace_id, name, widget_id) VALUES"
            " (current_setting('app.workspace_id')::uuid, 'Orphan', 999999999)",
        )
    # ranges are checked by the API, not by a database constraint: the row is stored
    in_workspace(
        mini_cluster,
        api,
        ws,
        "UPDATE kit_sample.widgets SET starts_on = '2026-12-01', ends_on = '2026-11-01'"
        " WHERE id = %s",
        (widget_id,),
    )


def test_row_level_security_hides_and_refuses_other_workspaces(mini_cell, mini_cluster):
    api = mini_cell.role("api")
    owner, stranger = uuid.uuid4(), uuid.uuid4()
    in_workspace(
        mini_cluster,
        api,
        owner,
        "INSERT INTO kit_sample.widgets (workspace_id, title) VALUES"
        " (current_setting('app.workspace_id')::uuid, 'Private')",
    )
    [(visible,)] = in_workspace(
        mini_cluster,
        api,
        stranger,
        "SELECT count(*) FROM kit_sample.widgets WHERE title = 'Private'",
    )
    assert visible == 0

    # writing a row for another workspace than the bound one is refused by WITH CHECK
    with pytest.raises(psycopg.errors.InsufficientPrivilege):
        in_workspace(
            mini_cluster,
            api,
            stranger,
            "INSERT INTO kit_sample.widgets (workspace_id, title) VALUES (%s, 'Smuggled')",
            (str(owner),),
        )
    # with no workspace bound at all, nothing is visible
    with mini_cluster.connect(api) as conn:
        assert conn.execute("SELECT count(*) FROM kit_sample.widgets").fetchone() == (
            0,
        )


